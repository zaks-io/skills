import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import Ajv from "ajv";
import standaloneCode from "ajv/dist/standalone/index.js";
import { format } from "prettier";
import schema from "./planner-schema/input.mjs";
import { legacyStateSchema, oldCanonicalStateSchema } from "./planner-schema/migration.mjs";
import prettierConfig from "../prettier.config.mjs";

const root = path.resolve(import.meta.dirname, "..");
const check = process.argv.includes("--check");
// Validators ship to every downstream install. Prettier indentation roughly
// doubles their size, so they keep Ajv's own line breaks and skip formatting
// (see .prettierignore).
const compiler = () =>
  new Ajv({
    code: { source: true, esm: true, lines: true },
    allErrors: true,
    inlineRefs: false,
    strictRequired: false,
  });
const generated = (header, code) => {
  if (/\brequire\(|\bimport\s/.test(code)) {
    throw new Error("Generated planner validators must not depend on external runtime modules");
  }
  return `// ${header} Do not edit.\n${code}\n`;
};

const ajv = compiler();
ajv.addSchema(schema);
const exports = Object.fromEntries(
  ["Input", "Config", "State", "Observation"].map((name) => [
    `validate${name}`,
    name === "Input" ? schema.$id : `${schema.$id}#/definitions/${name.toLowerCase()}`,
  ]),
);
const migrationAjv = compiler();
migrationAjv.addSchema(legacyStateSchema).addSchema(oldCanonicalStateSchema);

const outputs = {
  "skills/ziw-orchestrate/scripts/planner-input-validator.mjs": generated(
    "Generated by pnpm generate:planner-contract.",
    standaloneCode(ajv, exports),
  ),
  "skills/ziw-orchestrate/scripts/state-migration-validator.mjs": generated(
    "Generated frozen migration classifiers.",
    standaloneCode(migrationAjv, {
      validateLegacyState: "migration-legacy",
      validateOldCanonicalState: "migration-canonical",
    }),
  ),
  "skills/ziw-orchestrate/references/planner-input.schema.json": await format(
    JSON.stringify(schema),
    { ...prettierConfig, parser: "json" },
  ),
};
for (const [relative, content] of Object.entries(outputs)) {
  const file = path.join(root, relative);
  if (check) {
    if (readFileSync(file, "utf8") !== content) {
      throw new Error(`${relative} is stale; run pnpm generate:planner-contract`);
    }
  } else {
    writeFileSync(file, content);
  }
}
console.log(
  check ? "Planner contract artifacts are current." : "Generated planner contract artifacts.",
);
